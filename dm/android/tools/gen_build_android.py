#!/usr/bin/env python3
# Take the host's source files / header paths from the actually expanded compile commands of dm/host/Makefile
# (make -n -B dmhost, the same source of truth dm/ios/tools/gen_build.py reads) and generate the Android
# build's inputs, without hand-copying lists: when the Makefile changes, the next Android build follows
# automatically. The Android differences are applied here, not in the Makefile:
#   - every Apple-platform source the Android build replaces is left out: the .m files (front_mac.m,
#     memstat.m, haptics_apple.m, nvn_mtl.m, nvn_refl.m, nvn_deswizzle_gpu.m, the Vulkan and OpenGL
#     HLE layers) and tex/nvn_fmt_mtl.c (the Metal format table, used only by nvn_mtl.m); their
#     counterparts live in dm/android/ji (front_android.c, memstat_android.c, haptics_android.c) and
#     dm/android/jni/nvn/nvn_vk.c (the Vulkan execution layer), which CMakeLists.txt adds
#   - nvn_thunks.S (the Mach-O counting trampolines) is regenerated for ELF by gen_protos.py --elf
#     (a C symbol's assembly name has no underscore there; the committed file is untouched)
#   - main.c is compiled with -Dmain=dm_main, as the iOS project compiles it
# Output: <out.cmake> setting DM_HOST_SOURCES (relative to the repository root), DM_HOST_INCLUDES and
# DM_HOST_MAIN_CFLAGS, included by dm/android/jni/CMakeLists.txt.
# Usage: gen_build_android.py <dm/host dir> <out.cmake>   (GAME comes from the environment)
import os, shlex, subprocess, sys

host, out = (os.path.abspath(a) for a in sys.argv[1:3])
subprocess.run(['make', '-s', '-C', host, 'game_profile'], check=True)   # generate the game profile header for real first (make -n below only prints; GAME comes from the environment)
cmd = subprocess.run(['make', '-s', '-n', '-B', '-C', host, 'dmhost'], capture_output=True, text=True, check=True).stdout
lines = [shlex.split(l) for l in cmd.splitlines() if l.lstrip().startswith('clang')]
lines.sort(key=lambda t: 'dmhost' not in t)   # the host's own link command first, then the per-file compiles of its libraries
srcs, incs = [], []
for toks in lines:
    for t in toks:
        if t.startswith('-I'):
            d = os.path.normpath(os.path.join(host, t[2:]))
            if d not in incs: incs.append(d)
        elif t.endswith(('.c', '.m', '.S')):
            s = os.path.normpath(os.path.join(host, t))
            if s not in srcs: srcs.append(s)
assert srcs, 'no source files in the compile command'
root = os.path.abspath(os.path.join(host, '..'))   # the dm/ directory: the .cmake prefixes ${DM}/, which CMakeLists sets to dm/
# The Android replacements (see the header comment); paths are printed relative to the repository root
skip = [s for s in srcs if s.endswith('.m') or os.path.basename(s) == 'nvn_fmt_mtl.c' or os.path.basename(s) == 'nvn_thunks.S']
keep = [s for s in srcs if s not in skip]
dup = sorted({s for s in keep if keep.count(s) > 1})
if dup: sys.exit('duplicate source files in the compile command (explicit Makefile entries overlapping a wildcard?): ' + ' '.join(dup))
main_c = [s for s in keep if os.path.basename(s) == 'main.c']
if len(main_c) != 1: sys.exit(f'expected exactly one main.c, found {len(main_c)}')
keep = [s for s in keep if os.path.basename(s) != 'main.c']
rel = lambda p: os.path.relpath(p, root)
with open(out, 'w') as f:
    f.write('# Generated by dm/android/tools/gen_build_android.py; do not edit (make -n -B dmhost is its source)\n')
    f.write('set(DM_HOST_SOURCES\n')
    for s in keep: f.write(f'  ${{DM}}/{rel(s)}\n')
    f.write(')\nset(DM_HOST_MAIN ${DM}/%s)\n' % rel(main_c[0]))
    f.write('set(DM_HOST_INCLUDES\n')
    for d in incs: f.write(f'  ${{DM}}/{os.path.relpath(d, root)}\n')
    f.write(')\n')
print(f'{len(keep)} host sources (+ main.c), {len(skip)} replaced by the Android counterparts, {len(incs)} include paths')
for s in skip: print('  replaced:', os.path.relpath(s, root))   # relative to dm/, as the sources above
